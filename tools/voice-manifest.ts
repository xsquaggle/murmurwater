/**
 * Writes the voice-line manifest for recording: docs/voice/voice-lines.json (one entry per line, with the
 * file to write and the text hash to record in public/audio/voice/voiced.json) and docs/voice/SCRIPT.md
 * (the same, readable, grouped by speaker). Run with `npm run voice`.
 * It also reports which recordings are missing or stale against the current text.
 */
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { allVoiceLines, textHash } from '../src/game/talk';
import { NPCS } from '../src/core/quests';

const lines = allVoiceLines().map((l) => ({
  key: l.voice, file: `public/audio/voice/${l.voice}.mp3`, npc: l.npc, speaker: l.speaker, voiceStyle: l.voiceStyle,
  text: l.text, hash: textHash(l.text),
}));
mkdirSync('docs/voice', { recursive: true });
writeFileSync('docs/voice/voice-lines.json', JSON.stringify({ count: lines.length, lines }, null, 2) + '\n');

const voicedPath = 'public/audio/voice/voiced.json';
const voiced: Record<string, string> = existsSync(voicedPath) ? JSON.parse(readFileSync(voicedPath, 'utf8')) : {};
const state = (l: (typeof lines)[number]) => !existsSync(l.file) ? 'missing' : voiced[l.key] !== l.hash ? 'stale' : 'ok';

let md = `# Voice script\n\nGenerated by \`npm run voice\` from the quest and NPC data; do not edit by hand.\n` +
  `${lines.length} lines. Each file goes to \`public/audio/voice/<key>.mp3\`, and its key and hash go into \`public/audio/voice/voiced.json\` ` +
  `as \`{ "<key>": "<hash>" }\`. The game only plays a file whose recorded hash matches the line's current text.\n`;
for (const n of NPCS) {
  const mine = lines.filter((l) => l.npc === n.id);
  if (!mine.length) continue;
  md += `\n## ${n.name} (${n.role})\n\nVoice: ${n.voice}.\n\n| Key | Hash | Status | Line |\n|---|---|---|---|\n`;
  for (const l of mine) md += `| \`${l.key}\` | ${l.hash} | ${state(l)} | ${l.text.replace(/\|/g, '\\|')} |\n`;
}
writeFileSync('docs/voice/SCRIPT.md', md);
const counts = { ok: 0, missing: 0, stale: 0 };
for (const l of lines) counts[state(l)]++;
console.log(`voice lines: ${lines.length} (${counts.ok} recorded, ${counts.missing} missing, ${counts.stale} stale)`);
